-- Portable between PostgreSQL and H2 in PostgreSQL mode.

CREATE TABLE users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(254) NOT NULL,
    display_name   VARCHAR(64)  NOT NULL,
    password_hash  VARCHAR(100) NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email)
);

-- Only SHA-256 hashes of refresh tokens are stored.
CREATE TABLE refresh_tokens (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash   VARCHAR(64)  NOT NULL,
    family_id    VARCHAR(36)  NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at   TIMESTAMP WITH TIME ZONE,
    replaced_by  VARCHAR(64),
    CONSTRAINT uq_refresh_token_hash UNIQUE (token_hash)
);
CREATE INDEX ix_refresh_tokens_user ON refresh_tokens (user_id);
CREATE INDEX ix_refresh_tokens_family ON refresh_tokens (family_id);

CREATE TABLE password_reset_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash  VARCHAR(64) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at     TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_reset_token_hash UNIQUE (token_hash)
);
CREATE INDEX ix_reset_tokens_user ON password_reset_tokens (user_id);

CREATE TABLE reviews (
    id                VARCHAR(40)  PRIMARY KEY,
    user_id           BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    lang              VARCHAR(16)  NOT NULL,
    filename          VARCHAR(255),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    overall           INTEGER      NOT NULL,
    efficiency        INTEGER      NOT NULL,
    time_complexity   VARCHAR(40)  NOT NULL,
    space_complexity  VARCHAR(40)  NOT NULL,
    engine            VARCHAR(40)  NOT NULL,
    sample            BOOLEAN      NOT NULL DEFAULT FALSE,
    result_json       TEXT         NOT NULL,
    source_code       TEXT
);
CREATE INDEX ix_reviews_user_created ON reviews (user_id, created_at DESC);

CREATE TABLE progress (
    user_id     BIGINT PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    data_json   TEXT   NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    version     BIGINT NOT NULL DEFAULT 0
);
